import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;
import 'package:stock_management/Config/api_config.dart';
import 'package:stock_management/Model/request_models.dart';
import 'package:stock_management/Services/api_client.dart';
import 'package:stock_management/Services/image_upload.dart';

/// Requests (the certify / approve workflow) against the NestJS API.
class RequestService {
  RequestService({ApiClient? apiClient}) : _apiClient = apiClient ?? ApiClient();

  final ApiClient _apiClient;

  /// `GET /requests` is paginated (max 100 per page) — walk every page.
  /// Returns the raw JSON rows; the controller turns them into
  /// [RequestItemData] once it also has the master-data names.
  Future<List<Map<String, dynamic>>> fetchAll() async {
    final rows = <Map<String, dynamic>>[];
    var page = 1;
    while (true) {
      final json = await _apiClient.get(ApiConfig.requests, query: {'page': page, 'limit': 100}) as Map<String, dynamic>;
      final data = json['data'] as List? ?? const [];
      rows.addAll(data.map((e) => Map<String, dynamic>.from(e as Map)));
      final meta = json['meta'] as Map<String, dynamic>? ?? const {};
      if (meta['hasNextPage'] != true) break;
      page++;
    }
    return rows;
  }

  Future<Map<String, dynamic>> fetchOne(String id) async {
    final json = await _apiClient.get(ApiConfig.requestById(id));
    return Map<String, dynamic>.from(json as Map);
  }

  /// People the requester may put in the approval chain.
  Future<List<ApproverCandidate>> approverCandidates() async {
    final json = await _apiClient.get(ApiConfig.requestApproverCandidates);
    final list = json is List ? json : (json as Map<String, dynamic>)['data'] as List? ?? const [];
    return list.map((e) => ApproverCandidate.fromJson(Map<String, dynamic>.from(e as Map))).toList();
  }

  /// `POST /requests` for a new product (needs REQUEST_CREATE). [approvers]
  /// is the ordered chain: `[{userId, actionType: CERTIFIER|APPROVER}, ...]`.
  /// Product code and SKU are generated by the server.
  Future<void> createProductRequest({
    required Map<String, dynamic> product,
    List<Map<String, dynamic>> variants = const [],
    required List<Map<String, dynamic>> stock,
    required List<Map<String, dynamic>> approvers,
    File? image,
    String? remark,
  }) async {
    final fields = <String, String>{
      'requestType': 'PRODUCT_CREATE',
      'product': jsonEncode(product),
      'variants': jsonEncode(variants),
      'stock': jsonEncode(stock),
      'approvers': jsonEncode(approvers),
      if (remark != null && remark.trim().isNotEmpty) 'remark': remark.trim(),
    };
    final files = <http.MultipartFile>[];
    if (image != null) {
      files.add(await imageMultipart('image', image));
    }
    await _apiClient.postMultipart(ApiConfig.requests, fields: fields, files: files);
  }

  /// `POST /requests` for a stock movement — [requestType] is STOCK_IN,
  /// STOCK_OUT, STOCK_TRANSFER or STOCK_ADJUSTMENT. Pass [stock] rows for
  /// in / out / transfer, or [adjustments] rows for an adjustment (the shapes
  /// the API validates). [approvers] is the ordered chain.
  Future<void> createStockRequest({
    required String requestType,
    List<Map<String, dynamic>> stock = const [],
    List<Map<String, dynamic>> adjustments = const [],
    required List<Map<String, dynamic>> approvers,
    String? remark,
  }) async {
    final fields = <String, String>{
      'requestType': requestType,
      if (stock.isNotEmpty) 'stock': jsonEncode(stock),
      if (adjustments.isNotEmpty) 'adjustments': jsonEncode(adjustments),
      'approvers': jsonEncode(approvers),
      if (remark != null && remark.trim().isNotEmpty) 'remark': remark.trim(),
    };
    await _apiClient.postMultipart(ApiConfig.requests, fields: fields);
  }

  /// `POST /requests/:id/commit` — the signed-in approver's decision.
  Future<void> commit(String id, {required bool approve, String? remark}) async {
    await _apiClient.post(
      ApiConfig.requestCommit(id),
      body: {
        'action': approve ? 'APPROVE' : 'REJECT',
        if (remark != null && remark.trim().isNotEmpty) 'remark': remark.trim(),
      },
    );
  }
}
